bool exec(const fs::path& db_path, const std::string& sql) {
  sqlite3* db = nullptr;
  if (sqlite3_open(db_path.string().c_str(), &db) != SQLITE_OK) return false;
  const bool ok = sqlite3_exec(db, sql.c_str(), nullptr, nullptr, nullptr) == SQLITE_OK;
  sqlite3_close(db);
  return ok;
}

bool copy_out(const std::string& s, char* out, std::uint32_t capacity) {
  if (!out || s.size() + 1 > capacity) return false;
  std::memcpy(out, s.c_str(), s.size() + 1);
  return true;
}

