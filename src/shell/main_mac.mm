@interface MvLabApp : NSObject <NSApplicationDelegate, NSWindowDelegate>
@property(nonatomic, strong) NSWindow* window;
@property(nonatomic, strong) MvMetalView* view;
@property(nonatomic, strong) NSView* commandBar;
@end

@implementation MvLabApp {
  mv::shell::present_lab_mac _lab;
  mv::shell::input_snapshot _snap;
  mv::job_system _jobs;
  mv::shell::mac_lab_options _options;
  bool _terminating;
}
- (instancetype)initWithOptions:(const mv::shell::mac_lab_options&)options {
  self = [super init];
  if (self) _options = options;
  return self;
}
- (void)applicationDidFinishLaunching:(NSNotification*)notification {
  (void)notification;
  NSRect rect = NSMakeRect(0, 0, 1280, 720);
  self.window = [[NSWindow alloc]
      initWithContentRect:rect
                styleMask:NSWindowStyleMaskTitled | NSWindowStyleMaskClosable |
                          NSWindowStyleMaskMiniaturizable | NSWindowStyleMaskResizable
                  backing:NSBackingStoreBuffered
                    defer:NO];
  self.window.title = @"MediaViewer present lab";
  self.window.delegate = self;
  [self.window center];

  // PR 18: contentView becomes a plain container holding two siblings — the
  // Metal canvas (full bounds, unchanged from PR 16/17) and the SwiftUI
  // command bar pinned to the top strip, drawn over the canvas's top pixels.
  // Neither view is resized to make room for the other; syncSize keeps
  // publishing the canvas's own full backing size, and chrome_height_px
  // tells the render thread how much of it the bar visually covers.
  NSView* container = [[NSView alloc] initWithFrame:rect];
  self.window.contentView = container;

  self.view = [[MvMetalView alloc] initWithFrame:container.bounds];
  self.view.autoresizingMask = NSViewWidthSizable | NSViewHeightSizable;
  self.view.lab = &_lab;
  self.view.snap = &_snap;
  [container addSubview:self.view];

  self.commandBar = [MVChromeHost makeCommandBarView];
  [container addSubview:self.commandBar];
  [NSLayoutConstraint activateConstraints:@[
    [self.commandBar.leadingAnchor constraintEqualToAnchor:container.leadingAnchor],
    [self.commandBar.trailingAnchor constraintEqualToAnchor:container.trailingAnchor],
    [self.commandBar.topAnchor constraintEqualToAnchor:container.topAnchor],
    [self.commandBar.heightAnchor constraintEqualToConstant:kChromeBarHeightPoints],
  ]];

  g_chrome_snap = &_snap;
  g_chrome_lab = &_lab;

  _snap.window_visible = YES;
  _snap.window_active = YES;
  [self.view syncSize];

  if (auto started = _jobs.start(); !mv::ok(started)) {
    MV_LOG_ERROR("job_system failed to start");
    [NSApp terminate:nil];
    return;
  }
  _options.jobs = &_jobs;
  if (auto started = _lab.start((__bridge void*)self.view, _options); !started) {
    MV_LOG_ERROR("present lab failed to start");
    [NSApp terminate:nil];
    return;
  }
  [self.window makeKeyAndOrderFront:nil];
  [NSApp activateIgnoringOtherApps:YES];
}
- (BOOL)applicationShouldTerminateAfterLastWindowClosed:(NSApplication*)sender {
  (void)sender;
  return YES;
}
- (void)windowWillClose:(NSNotification*)notification {
  (void)notification;
  // Command-bar buttons stop reaching the lab first: they only poke _snap
  // through the g_chrome_* globals, so clearing those before teardown means
  // a button click racing window close can never touch a torn-down lab.
  // This is the only work windowWillClose does -- it runs on the main
  // thread and must not block it (CLAUDE.md rule 1). The actual teardown
  // (job_system::shutdown() joining workers, _lab.stop() joining the render
  // thread) can take as long as an in-flight decode+upload job does, so it
  // runs off the main thread in -applicationShouldTerminate: instead, which
  // fires only after the window has already closed.
  g_chrome_snap = nullptr;
  g_chrome_lab = nullptr;
}
- (NSApplicationTerminateReply)applicationShouldTerminate:(NSApplication*)sender {
  (void)sender;
  if (_terminating) return NSTerminateLater;
  _terminating = true;
  // Jobs first: submit_image_load()'s job holds a raw (non-retaining)
  // id<MTLDevice> pointer, so it must finish before _lab.stop() reaches
  // device_.destroy() on the render thread -- shutdown() drains queued jobs
  // and joins running ones, so this ordering guarantees that. Both block,
  // so both run on a background queue; the window is already closed by the
  // time this method runs, so nothing user-visible waits on it.
  dispatch_async(dispatch_get_global_queue(DISPATCH_QUEUE_PRIORITY_DEFAULT, 0), ^{
    _jobs.shutdown();
    _lab.stop();
    dispatch_async(dispatch_get_main_queue(), ^{
      [NSApp replyToApplicationShouldTerminate:YES];
    });
  });
  return NSTerminateLater;
}
- (void)windowDidChangeOcclusionState:(NSNotification*)notification {
  (void)notification;
  _snap.window_visible = (self.window.occlusionState & NSWindowOcclusionStateVisible) != 0;
  [self.view publish];
  _lab.wake();
}
- (void)windowDidBecomeKey:(NSNotification*)notification {
  (void)notification;
  _snap.window_active = true;
  [self.view publish];
}
- (void)windowDidResignKey:(NSNotification*)notification {
  (void)notification;
  _snap.window_active = false;
  [self.view publish];
}
- (int)exitCode {
  return _lab.exit_code();
}
@end

namespace {

void usage() {
  std::fprintf(stderr,
               "mediaviewer_lab — Metal present lab (PR 16), still decode + pan/zoom (PR 17)\n"
               "  --soak N --json PATH [--gate] [--static] [--no-overlay]\n"
               "  --open PATH   decode a JPEG/PNG/BMP and fit it; wheel to zoom toward the\n"
               "                cursor, drag to pan, 0 fit, 1 one-to-one\n");
}

}  // namespace

int main(int argc, char** argv) {
  mv::trace::provider_register();
  mv::shell::mac_lab_options options;
  for (int i = 1; i < argc; ++i) {
    const char* arg = argv[i];
    auto next = [&]() -> const char* { return i + 1 < argc ? argv[++i] : ""; };
    if (std::strcmp(arg, "--soak") == 0) {
      options.soak_seconds = std::strtod(next(), nullptr);
    } else if (std::strcmp(arg, "--json") == 0) {
      options.json_report_path = next();
    } else if (std::strcmp(arg, "--gate") == 0) {
      options.gate_exit_code = true;
    } else if (std::strcmp(arg, "--static") == 0) {
      options.start_animating = false;
    } else if (std::strcmp(arg, "--no-overlay") == 0) {
      options.overlay_visible = false;
    } else if (std::strcmp(arg, "--open") == 0) {
      options.open_path = next();
    } else if (std::strcmp(arg, "--help") == 0 || std::strcmp(arg, "-h") == 0) {
      usage();
      return 0;
    } else {
      std::fprintf(stderr, "mediaviewer_lab: unrecognised argument %s\n", arg);
      usage();
      return 2;
    }
  }
  if (options.soak_seconds > 0.0) {
    bool saw_static = false;
    for (int i = 1; i < argc; ++i) {
      if (std::strcmp(argv[i], "--static") == 0) saw_static = true;
    }
    options.start_animating = !saw_static;
  }

  @autoreleasepool {
    [NSApplication sharedApplication];
    [NSApp setActivationPolicy:NSApplicationActivationPolicyRegular];
    MvLabApp* app = [[MvLabApp alloc] initWithOptions:options];
    NSApp.delegate = app;
    [NSApp run];
    const int code = [app exitCode];
    mv::trace::provider_unregister();
    return code;
  }
}
