      if (!clip) return NO;
      _snap.video_speed_steps += command == rate_up ? 1 : -1; [self pokeSnapshot]; return YES;
    case mute:
      if (!clip) return NO;
      ++_snap.video_mute_seq; [self pokeSnapshot]; return YES;
