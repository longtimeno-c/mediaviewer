static BOOL MvCopyUtf8(const std::string& text, char* buf, int32_t size) {
  const std::size_t n = std::min(text.size(), static_cast<std::size_t>(size) - 1);
  std::memcpy(buf, text.data(), n);
  buf[n] = '\0';
  return YES;
}

