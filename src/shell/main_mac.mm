// `navigation` = moving through the folder tree the user already opened (a
// folder tile, a breadcrumb, up): the trail keeps its root and the filmstrip
// setting is left alone. NO = a fresh open (Open, a drop, the CLI), which
// starts a new trail.
- (BOOL)openPath:(const char*)utf8_path navigation:(BOOL)navigation {
  if (!utf8_path || !*utf8_path) return NO;
  const std::string path(utf8_path);
  // A single stat() to answer "does anything exist here" is the one I/O
  // this method does inline -- cheap and synchronous by nature, the same
  // exception every "no I/O on the UI thread" codebase makes for a stat
  // call, unlike the real I/O folder_model::open() below does.
  auto is_dir = mv::io::is_directory(path);
  if (!is_dir) return NO;  // stat failed: nothing exists at this path

  std::string dir;
  std::string select_path;
  if (is_dir.value()) {
    dir = path;
  } else {
    auto containing = mv::io::containing_dir(path);
    if (!containing) return NO;
    dir = containing.value();
    select_path = path;
  }
  // Moving up into a folder that contains the one we are leaving: remember
  // that child so its tile is selected when the parent listing arrives.
  if (navigation && !_currentDir.empty() && dir != _currentDir &&
      mv::shell::browse_path::within(_currentDir, dir)) {
    _revealChild = _currentDir;
  } else {
    _revealChild.clear();
  }
  // The destination is one of the folders on screen: those paths are its
  // siblings, already in memory, so sideways navigation does not wait.
  bool seeded = false;
  for (std::size_t i = 0; i < _subdirs.size(); ++i) {
    if (_subdirs[i].path_utf8 != dir) continue;
    _siblings.clear();
    _siblings.reserve(_subdirs.size());
    for (const auto& sub : _subdirs) _siblings.push_back(sub.path_utf8);
    _siblingIndex = static_cast<NSInteger>(i);
    seeded = true;
    break;
  }
  if (!seeded) {
    bool kept = false;
    for (std::size_t i = 0; i < _siblings.size(); ++i) {
      if (_siblings[i] == dir) {
        _siblingIndex = static_cast<NSInteger>(i);
        kept = true;
        break;
      }
    }
    if (!kept) {
      _siblings.clear();
      _siblingIndex = -1;
    }
  }
  _folderFind = NO;
  _folderQuery.clear();
  if (navigation) {
    _browsePath.visit(dir);
  } else {
    _browsePath.reset(dir);
  }
  _folderCursor = -1;
  _subdirs.clear();
  _galleryIfEmptyDir = dir;
  // Settings: a folder open earns the filmstrip; opening one image is a viewing
  // intent and keeps it off until asked (plan/16, same as Windows).
  if (!navigation) {
    const auto prefs = mv::shell::view_settings::from_flags(_viewFlags);
    const BOOL want = is_dir.value() ? prefs.filmstrip_for_folder : prefs.filmstrip_for_image;
    if (want != _filmstripVisible) [self setFilmstripVisible:want];
  }

  // The listing itself is already async (folder_model_mac::relist_async
  // submits its own job); -refreshFolderIfChanged picks it up once
  // consume_changed() fires and resolves `_wantSelectedPath` against the
  // real listing. Resetting `_index`/`_items` now, synchronously (no I/O
  // here, just clearing C++ containers), means a relist that lands for a
  // *different* folder in flight can never be mistaken for this one's.
  _wantSelectedPath = select_path;
  _currentDir = dir;
  _items.clear();
  _index.reset(0);
  _metaRecord.reset();
  ++_metaGeneration;

  // folder_model::open() itself is real I/O -- opening, and maybe creating,
  // the thumbnail cache's SQLite file -- so it never runs on the UI thread
  // (CLAUDE.md rule 1: "no I/O"), unlike the is_directory() stat above.
  // `&_folder`/`&_jobs` stay valid for the job's duration because MvLabApp
  // is never destroyed before the process exits -- unlike folder_model_mac's
  // own internal jobs, which capture a shared_ptr<shared_state> precisely
  // because a folder_model *can* be destroyed mid-job in general.
  mv::shell::folder_model* folder = &_folder;
  mv::job_system* jobs = &_jobs;
  const std::uint64_t my_generation = _openGeneration.fetch_add(1, std::memory_order_acq_rel) + 1;
  std::atomic<std::uint64_t>* open_generation = &_openGeneration;
  _jobs.submit_at(mv::background_generation,
                  [folder, jobs, dir, my_generation, open_generation](
                      const mv::job_context&) -> mv::status {
                    // A newer -openEntryPath: call already arrived: calling
                    // folder->open() now would race that one's own open()
                    // call outside folder_model's internal locking (see
                    // _openGeneration's declaration comment). Let the newer
                    // request own this folder_model unopposed instead.
                    if (open_generation->load(std::memory_order_acquire) != my_generation) {
                      return mv::status::cancelled;
                    }
                    auto opened = folder->open(dir, *jobs);
                    if (!opened) {
                      dispatch_async(dispatch_get_main_queue(), ^{
                        NSBeep();
                      });
                      return opened.error();
                    }
                    return mv::status::ok;
                  });
  [self updateChromeBarHeight];
  return YES;
}

- (void)refreshFolderIfChanged {
  if (!_askedDefaultViewer && _options.soak_seconds <= 0.0) {
    [self askDefaultViewerOnce];
  }
  // The transport strip belongs to a clip: shown while one is on screen (the
  // render thread publishes that), hidden otherwise so it never blocks the
  // canvas's mouse. Polled here, on the 0.2 s timer that already exists.
  if (self.transportHost) {
    const bool active = g_chrome_lab && g_chrome_lab->video_status_snapshot().active;
    if (self.transportHost.hidden == active) self.transportHost.hidden = !active;
  }
  // Date-taken keys arriving on the pool re-sort the listing in place: the same
  // items, the current one still selected, no image reload.
  if (_meta.consume_dates_changed() && _sort.key == mv::io::sort_key::date_taken) {
    [self resortKeepingSelection];
  }
  if (!_folder.consume_changed()) return;
  _items = _folder.items();
  _subdirs = _folder.subfolders();
  if (_folderCursor >= static_cast<NSInteger>(_subdirs.size())) {
    _folderCursor = static_cast<NSInteger>(_subdirs.size()) - 1;
  }
  [self sortItems];
  ++_listingGeneration;

  // Marks are kept by path specifically so they survive a relist that
  // merely reorders _items, but a path can also drop out of the listing
  // entirely here -- external deletion/rename, not just this app's own
  // copy/move/Trash (which already prune their own successes directly).
  // Without this, a mark for a file that is simply gone would sit in
  // _marks forever, inflating _snap.marked_count.
  if (!_marks.empty()) {
    std::set<std::string> live_paths;
    for (const auto& entry : _items) live_paths.insert(entry.path_utf8);
    std::erase_if(_marks, [&live_paths](const std::string& path) {
      return !live_paths.count(path);
    });
    ++_marksGeneration;
  }

  std::size_t new_index = 0;
  if (!_items.empty()) {
    bool found = false;
    if (!_wantSelectedPath.empty()) {
      for (std::size_t i = 0; i < _items.size(); ++i) {
        if (_items[i].path_utf8 == _wantSelectedPath) {
          new_index = i;
          found = true;
          break;
        }
      }
    }
    if (!found) {
      new_index = std::min(_index.current(), _items.size() - 1);
    }
  }
  [self selectIndex:new_index];

  bool revealed = false;
  if (!_revealChild.empty()) {
    for (std::size_t i = 0; i < _subdirs.size(); ++i) {
      if (_subdirs[i].path_utf8 == _revealChild) {
        _folderCursor = static_cast<NSInteger>(i);
        revealed = true;
        break;
      }
    }
    _revealChild.clear();
  }

  // A folder that holds only folders opens the gallery so the tiles are what
  // the user lands on. Coming back up also opens it, on the tile that was left.
  if (!_galleryIfEmptyDir.empty() && _folder.directory() == _galleryIfEmptyDir) {
    _galleryIfEmptyDir.clear();
    if (_items.empty() && !_subdirs.empty()) {
      [self setGalleryVisible:YES];
      if (!revealed) _folderCursor = 0;
    }
  }
  if (revealed) [self setGalleryVisible:YES];
  [self refreshSiblings];
}

- (void)selectIndex:(std::size_t)new_index {
  _index.reset(_items.size(), new_index);

  if (_items.empty()) {
    _wantSelectedPath.clear();
    _edits.clear_item();
    _itemId = 0;
    [self publishEdit];
    _snap.item_index = 0;
    _snap.item_count = 0;
    _snap.item_name[0] = '\0';
  } else {
    const mv::io::dir_entry& entry = _items[_index.current()];
    _wantSelectedPath = entry.path_utf8;
    [self editItemOpened:entry item:_lab.open_item(entry.path_utf8)];
    _snap.item_index = static_cast<std::uint32_t>(_index.current());
    _snap.item_count = static_cast<std::uint32_t>(_items.size());
    const std::size_t n = std::min(entry.name_utf8.size(), sizeof(_snap.item_name) - 1);
    std::memcpy(_snap.item_name, entry.name_utf8.data(), n);
    _snap.item_name[n] = '\0';
  }
  [self updateMarkSnapshot];
  [self metadataSelectionChanged];
  [self publish];
}

// input_snapshot.item_marked/marked_count (src/shell/input_state.h) refresh
