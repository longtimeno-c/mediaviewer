          _edits.cancel_crop();
          [self publishEdit];
          [self pokeSnapshot];
          break;
        case mv::shell::back_target::pane:
          [self setMetaPaneVisible:NO];
          [self setTreeVisible:NO];
          [self setAdjustVisible:NO];
          break;
        case mv::shell::back_target::slideshow: [self leaveSlideshow]; break;
        case mv::shell::back_target::fullscreen: [self toggleFullscreen]; break;
        case mv::shell::back_target::game:
          _gameOn = NO;
          ++_snap.game_exit_seq;
          [self pokeSnapshot];
          break;
        default: break;
      }
      return YES;
    case toggle_gallery: [self toggleGallery]; return YES;
    case toggle_filmstrip: [self toggleFilmstrip]; return YES;
    case gallery_up: [self galleryMoveRows:-1]; return YES;
    case gallery_down: [self galleryMoveRows:1]; return YES;
    case gallery_open_selected:
      if (_galleryVisible && _folderCursor >= 0) {
        [self openSubfolderAtIndex:_folderCursor];
        return YES;
      }
      [self setGalleryVisible:NO];
      return YES;
    case folder_up: return [self navigateUp];
    case folder_prev: return [self navigateSibling:-1];
    case folder_next: return [self navigateSibling:1];
    case typeahead: {
