// Bridge target for mv_chrome_fit()/mv_chrome_one_to_one() (declared in
// src.swift/MediaViewerChrome/Sources/MVChromeBridge, called from
// CommandBarView.swift). Set once in -applicationDidFinishLaunching:, same
// lifetime as the window; the lab and its snapshot outlive the app delegate
// only because both are ivars of the single MvLabApp instance that owns this
// process's only window (plan/14-abi.md's shape, scoped to the lab).
mv::shell::input_snapshot* g_chrome_snap = nullptr;
mv::shell::present_lab_mac* g_chrome_lab = nullptr;
}  // namespace

// [any-thread] SwiftUI runs button actions on the main actor, so these run
// on the main thread in practice; they only ever touch input_snapshot the
// same way MvMetalView's event handlers do (edge-triggered counter bump,
// then wake), so there is nothing here that requires it.
extern "C" void mv_chrome_fit(void) {
  if (!g_chrome_snap) return;
  ++g_chrome_snap->fit_seq;
  if (g_chrome_lab) g_chrome_lab->wake();
}
extern "C" void mv_chrome_one_to_one(void) {
  if (!g_chrome_snap) return;
  ++g_chrome_snap->one_to_one_seq;
  if (g_chrome_lab) g_chrome_lab->wake();
}

// Command-bar strip height, in points (converted to backing pixels via the
// window's backingScaleFactor before it reaches input_snapshot.chrome_height_px
// — that field, and every canvas-rect field alongside it, is already in
// physical pixels, matching Windows' PerMonitorV2 convention).
constexpr CGFloat kChromeBarHeightPoints = 44.0;

@interface MvMetalView : NSView
