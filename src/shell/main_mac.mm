- (void)windowWillClose:(NSNotification*)notification {
  (void)notification;
  // Command-bar buttons stop reaching the lab first: they only poke _snap
  // through the g_chrome_* globals, so clearing those before teardown means
  // a button click racing window close can never touch a torn-down lab.
  // This is the only work windowWillClose does -- it runs on the main
  // thread and must not block it (CLAUDE.md rule 1). The actual teardown
  // (job_system::shutdown() joining workers, _lab.stop() joining the render
  // thread) can take as long as an in-flight decode+upload job does, so it
  // runs off the main thread in -applicationShouldTerminate: instead, which
  // fires only after the window has already closed.
  g_chrome_snap = nullptr;
  g_chrome_lab = nullptr;
  g_chrome_app = nullptr;
  [_folderPollTimer invalidate];
  _folderPollTimer = nil;
  // _slideshowTimer's target is self, retained by NSTimer until invalidated
  // -- nulling g_chrome_app above does not stop it, since it calls
  // -navigateNext directly rather than through the bridge globals. Left
  // running, it would keep firing -navigateNext/-selectIndex: on a
  // half-torn-down MvLabApp after the window (and _folder) are gone, racing
  // -applicationShouldTerminate:'s own off-main-thread teardown. Not
  // routed through -leaveSlideshow: that also un-fullscreens the window,
  // which is unnecessary work on a window that is already closing.
  [_slideshowTimer invalidate];
  _slideshowTimer = nil;
  _slideshowActive = NO;
  _slideshowPaused = NO;
  // Stops and joins the FSEvents watch thread; safe on the main thread per
  // io/dir.h's contract, and cheap -- in-flight relist/thumb jobs keep their
  // own shared_ptr<shared_state> and finish safely regardless (folder_model_mac.h).
  _folder.close();
}
- (NSApplicationTerminateReply)applicationShouldTerminate:(NSApplication*)sender {
  (void)sender;
  if (_terminating) return NSTerminateLater;
  _terminating = true;
  // Jobs first: submit_image_load()'s job holds a raw (non-retaining)
  // id<MTLDevice> pointer, so it must finish before _lab.stop() reaches
  // device_.destroy() on the render thread -- shutdown() drains queued jobs
  // and joins running ones, so this ordering guarantees that. Both block,
  // so both run on a background queue; the window is already closed by the
  // time this method runs, so nothing user-visible waits on it.
  dispatch_async(dispatch_get_global_queue(DISPATCH_QUEUE_PRIORITY_DEFAULT, 0), ^{
    _jobs.shutdown();
    _lab.stop();
    // Not dispatch_async(main queue): while NSTerminateLater is pending,
    // -[NSApplication terminate:] spins a nested run loop in a mode that does
    // not service the main dispatch queue, so that block never ran and the
    // process never exited (found on real hardware, 2026-09-19: every
    // --soak run, and so frametime, timed out after writing its report).
    // Performing the block in the common modes runs in whichever mode the
    // wait is in.
    CFRunLoopPerformBlock(CFRunLoopGetMain(), kCFRunLoopCommonModes, ^{
      [NSApp replyToApplicationShouldTerminate:YES];
    });
    CFRunLoopWakeUp(CFRunLoopGetMain());
  });
  return NSTerminateLater;
}
