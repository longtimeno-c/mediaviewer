}
- (void)mouseUp:(NSEvent*)event {
  (void)event;
  self.snap->mouse_down[0] = false;
  ++self.snap->activity_seq;
  [self publish];
  if (self.lab) self.lab->wake();
}
- (void)rightMouseDown:(NSEvent*)event {
  (void)event;
  self.snap->mouse_down[1] = true;
  ++self.snap->activity_seq;
