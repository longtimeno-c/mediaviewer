    case move_to_pick: [self moveMarkedPickDestination:YES]; return YES;
    case delete_to_recycle_bin:
      if (_items.empty()) return NO;
      [self deleteMarkedToTrash];
      return YES;
    case slideshow_start:
      if (_items.empty()) return NO;
      [self startSlideshow];
      return YES;
