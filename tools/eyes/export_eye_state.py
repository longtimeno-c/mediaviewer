"""Writes src/edit/eye_state_weights.inc from OpenVINO Open Model Zoo's
open-closed-eye-0001 (Apache-2.0, Intel), the ONNX file at

  https://storage.openvinotoolkit.org/repositories/open_model_zoo/public/2022.1/open-closed-eye-0001/open_closed_eye.onnx
  46164 bytes, SHA-384 2615bce53b55620c629db21b043057600ccc53466f053c0a8277c43577c2db21e48f330cf9b15213016d17cddb8cba27

    python3 tools/eyes/export_eye_state.py open_closed_eye.onnx src/edit/eye_state_weights.inc

Needs the `onnx` package. The graph is checked to be the one edit/eye_state.cpp
runs: conv 3x3 (3->10), max-pool 2, ReLU, conv 3x3 (10->20), max-pool 2, ReLU,
conv 3x3 (20->50), conv 1x1 (50->2, no bias), max-pool 4, softmax.
"""
import hashlib
import sys

import onnx
from onnx import numpy_helper

SHA384 = "2615bce53b55620c629db21b043057600ccc53466f053c0a8277c43577c2db21e48f330cf9b15213016d17cddb8cba27"
src, out = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
if hashlib.sha384(data).hexdigest() != SHA384:
    sys.exit("not the open-closed-eye-0001 file this was written for")
m = onnx.load_from_string(data)
ops = [n.op_type for n in m.graph.node]
if ops != ["Conv", "MaxPool", "Relu", "Conv", "MaxPool", "Relu", "Conv", "Conv", "MaxPool", "Exp", "ReduceSum", "Div"]:
    sys.exit(f"unexpected graph {ops}")
w = {i.name: numpy_helper.to_array(i) for i in m.graph.initializer}
want = {"conv1.weight": (10, 3, 3, 3), "conv1.bias": (10,), "conv2.weight": (20, 10, 3, 3), "conv2.bias": (20,),
        "conv3.weight": (50, 20, 3, 3), "conv3.bias": (50,), "conv4.weight": (2, 50, 1, 1)}
for k, s in want.items():
    if tuple(w[k].shape) != s:
        sys.exit(f"{k}: {w[k].shape}, want {s}")
with open(out, "w") as f:
    f.write("// Generated by tools/eyes/export_eye_state.py from OpenVINO Open Model Zoo\n")
    f.write("// open-closed-eye-0001 (Copyright Intel Corporation, Apache License 2.0;\n")
    f.write("// docs/design/11-licensing.md). Do not edit.\n")
    for k in want:
        name = "k" + "".join(p.capitalize() for p in k.replace(".", "_").split("_"))
        vals = w[k].astype("float32").ravel()
        f.write(f"constexpr float {name}[{len(vals)}] = {{\n")
        for i in range(0, len(vals), 8):
            f.write("    " + ", ".join(f"{float(v):.9g}f" for v in vals[i:i + 8]) + ",\n")
        f.write("};\n")
print("wrote", out)
