"""src/infer/wordpiece_strip.inc: BERT's "strip accents" (NFD, then nonspacing
marks dropped) beyond the scripts core/fold.h covers (#354 D3). Two tables from
Python's unicodedata: code points whose NFD is one or two base characters plus
marks (kana with dakuten, CJK compatibility ideographs, Indic two-part vowels),
and the ranges of category Mn. Hangul syllables decompose by formula in
text_models.cpp, so they are not listed.

    python3 -I tools/ai-reference/gen_wordpiece_tables.py > src/infer/wordpiece_strip.inc
"""
import unicodedata as u

FIRST = 0x0530  # Latin, Greek and Cyrillic below: core/fold.h


def main():
    dec, mn = [], []
    for cp in range(FIRST, 0x30000):
        c = chr(cp)
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        if u.category(c) == "Mn":
            mn.append(cp)
            continue
        base = [x for x in u.normalize("NFD", c) if u.category(x) != "Mn"]
        if base != [c] and 1 <= len(base) <= 2:
            dec.append((cp, ord(base[0]), ord(base[1]) if len(base) == 2 else 0))
    ranges = []
    for cp in mn:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    print(f"// Generated by tools/ai-reference/gen_wordpiece_tables.py (Unicode {u.unidata_version}). Do not edit.")
    print("#if defined(MV_WORDPIECE_DECOMPOSE)")
    for cp, a, b in dec:
        print(f"{{0x{cp:X}, 0x{a:X}, 0x{b:X}}},")
    print("#elif defined(MV_WORDPIECE_MARKS)")
    for a, b in ranges:
        print(f"{{0x{a:X}, 0x{b:X}}},")
    print("#endif")


if __name__ == "__main__":
    main()
