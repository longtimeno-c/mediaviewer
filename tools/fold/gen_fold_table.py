"""Generate src/core/fold_table.inc, the code-point table behind mv::fold() (core/fold.h).

    python3 -I tools/fold/gen_fold_table.py > src/core/fold_table.inc

The rule is the hosts' name fold (IslandHost.FileSearch.cs FoldName; Swift
`folding([.caseInsensitive, .diacriticInsensitive])`): decompose (NFD), drop
non-spacing marks, recompose, lowercase. Letters with no decomposition
(ł, ø, ß, æ, đ) stay themselves, lowercased, exactly as on the hosts. The
table covers the scripts place names use: Latin (incl. Extended-A/B and
Additional), Greek and Cyrillic. Combining marks U+0300-U+036F are dropped in
code, so a decomposed name folds like a precomposed one.
"""
import sys
import unicodedata

RANGES = [(0x00C0, 0x024F), (0x0370, 0x03FF), (0x0400, 0x052F), (0x1E00, 0x1EFF)]


def fold(ch):
    s = unicodedata.normalize("NFD", ch)
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    s = unicodedata.normalize("NFC", s).lower()
    s = unicodedata.normalize("NFD", s)
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    return unicodedata.normalize("NFC", s)


def main():
    rows = []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            ch = chr(cp)
            if unicodedata.category(ch) == "Cn":
                continue
            f = fold(ch)
            if f != ch and len(f) == 1:
                rows.append((cp, ord(f)))
            elif f == "" or unicodedata.category(ch) == "Mn":
                rows.append((cp, 0))
    out = sys.stdout
    out.write("// Copyright (C) 2026 longtimeno-c\n// SPDX-License-Identifier: GPL-3.0-or-later\n")
    out.write(f"// Generated by tools/fold/gen_fold_table.py (Unicode {unicodedata.unidata_version}). Do not edit.\n")
    out.write("// {code point, folded code point or 0 to drop}, sorted.\n")
    for cp, to in rows:
        out.write(f"{{0x{cp:04X}, 0x{to:04X}}},\n")


if __name__ == "__main__":
    main()
