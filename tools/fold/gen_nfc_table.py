"""Generates src/addons/ai/nfc_table.inc from Python's unicodedata.

One table in the repo, so every OS names a file the same way. The OS normalisers
differ by Unicode version; a phone and a desktop must not.

    python3 tools/fold/gen_nfc_table.py > src/addons/ai/nfc_table.inc
"""
import sys
import unicodedata as u

MAX = 0x110000


def skip(c: int) -> bool:
    return 0xD800 <= c <= 0xDFFF or 0xAC00 <= c <= 0xD7A3  # surrogates; Hangul is arithmetic


def main() -> None:
    decomp = []  # (code point, first, second or 0)
    ccc = []
    for c in range(MAX):
        if skip(c):
            continue
        ch = chr(c)
        d = u.decomposition(ch)
        if d and not d.startswith("<"):
            parts = [int(x, 16) for x in d.split()]
            decomp.append((c, parts[0], parts[1] if len(parts) > 1 else 0))
        k = u.combining(ch)
        if k:
            ccc.append((c, k))
    compose = []
    for c, a, b in decomp:
        if b and u.normalize("NFC", chr(a) + chr(b)) == chr(c):
            compose.append((a, b, c))
    compose.sort()
    out = sys.stdout
    out.write(f"// Generated by tools/fold/gen_nfc_table.py (Unicode {u.unidata_version}). Do not edit.\n")
    out.write("#if defined(MV_NFC_DECOMP)\n")
    for c, a, b in decomp:
        out.write(f"{{0x{c:X},0x{a:X},0x{b:X}}},\n")
    out.write("#elif defined(MV_NFC_CCC)\n")
    for c, k in ccc:
        out.write(f"{{0x{c:X},{k}}},\n")
    out.write("#elif defined(MV_NFC_COMPOSE)\n")
    for a, b, c in compose:
        out.write(f"{{0x{a:X},0x{b:X},0x{c:X}}},\n")
    out.write("#endif\n")


if __name__ == "__main__":
    main()
